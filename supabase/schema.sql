begin;

create extension if not exists pgcrypto;

-- ----------------------------------------------------------------------------
-- Perfis
-- ----------------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  nome text not null default 'Estudante',
  nivel text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ----------------------------------------------------------------------------
-- Progresso das aulas
-- ----------------------------------------------------------------------------
create table if not exists public.study_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  topico_id text not null,
  nivel text not null,
  materia text not null check (materia in ('portugues', 'matematica')),
  concluido boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, topico_id)
);

-- ----------------------------------------------------------------------------
-- Tentativas de quiz
-- ----------------------------------------------------------------------------
create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  nivel text not null,
  materia text not null check (materia in ('portugues', 'matematica')),
  topico_id text,
  acertos integer not null check (acertos >= 0),
  total integer not null check (total > 0),
  created_at timestamptz not null default now(),
  constraint quiz_attempts_acertos_total check (acertos <= total)
);

create index if not exists study_progress_user_idx
  on public.study_progress (user_id, updated_at desc);

create index if not exists quiz_attempts_user_idx
  on public.quiz_attempts (user_id, created_at desc);

create index if not exists quiz_attempts_created_idx
  on public.quiz_attempts (created_at desc);

-- ----------------------------------------------------------------------------
-- updated_at automático
-- ----------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
  before update on public.profiles
  for each row execute function public.set_updated_at();

drop trigger if exists study_progress_set_updated_at on public.study_progress;
create trigger study_progress_set_updated_at
  before update on public.study_progress
  for each row execute function public.set_updated_at();

-- ----------------------------------------------------------------------------
-- Cria o perfil automaticamente quando uma conta é cadastrada
-- ----------------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, nome, nivel)
  values (
    new.id,
    coalesce(
      nullif(trim(new.raw_user_meta_data ->> 'nome'), ''),
      split_part(coalesce(new.email, 'estudante'), '@', 1),
      'Estudante'
    ),
    nullif(trim(new.raw_user_meta_data ->> 'nivel'), '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Garante perfil para usuários que já existiam antes deste esquema.
insert into public.profiles (id, nome, nivel)
select
  u.id,
  coalesce(
    nullif(trim(u.raw_user_meta_data ->> 'nome'), ''),
    split_part(coalesce(u.email, 'estudante'), '@', 1),
    'Estudante'
  ),
  nullif(trim(u.raw_user_meta_data ->> 'nivel'), '')
from auth.users u
on conflict (id) do nothing;

-- ----------------------------------------------------------------------------
-- Row Level Security
-- ----------------------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.study_progress enable row level security;
alter table public.quiz_attempts enable row level security;

drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own"
  on public.profiles for select
  to authenticated
  using ((select auth.uid()) = id);

drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own"
  on public.profiles for insert
  to authenticated
  with check ((select auth.uid()) = id);

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own"
  on public.profiles for update
  to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

drop policy if exists "study_progress_select_own" on public.study_progress;
create policy "study_progress_select_own"
  on public.study_progress for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "study_progress_insert_own" on public.study_progress;
create policy "study_progress_insert_own"
  on public.study_progress for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "study_progress_update_own" on public.study_progress;
create policy "study_progress_update_own"
  on public.study_progress for update
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "study_progress_delete_own" on public.study_progress;
create policy "study_progress_delete_own"
  on public.study_progress for delete
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "quiz_attempts_select_own" on public.quiz_attempts;
create policy "quiz_attempts_select_own"
  on public.quiz_attempts for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "quiz_attempts_insert_own" on public.quiz_attempts;
create policy "quiz_attempts_insert_own"
  on public.quiz_attempts for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

-- ----------------------------------------------------------------------------
-- Ranking semanal
-- Função SECURITY DEFINER: devolve apenas dados agregados e públicos
-- (nome e pontos), sem expor e-mail, IDs ou respostas individuais.
-- ----------------------------------------------------------------------------
create or replace function public.ranking_semanal()
returns table (
  nome text,
  pontos bigint,
  acertos bigint,
  tentativas bigint
)
language sql
security definer
set search_path = public
as $$
  select
    p.nome,
    coalesce(sum(q.acertos * 10), 0)::bigint as pontos,
    coalesce(sum(q.acertos), 0)::bigint as acertos,
    count(q.id)::bigint as tentativas
  from public.profiles p
  inner join public.quiz_attempts q on q.user_id = p.id
  where q.created_at >= now() - interval '7 days'
  group by p.id, p.nome
  order by pontos desc, acertos desc, tentativas asc
  limit 10;
$$;

revoke all on function public.ranking_semanal() from public;
grant execute on function public.ranking_semanal() to authenticated;

-- ----------------------------------------------------------------------------
-- Permissões explícitas para usuários autenticados
-- ----------------------------------------------------------------------------
grant usage on schema public to authenticated;
grant select, insert, update on public.profiles to authenticated;
grant select, insert, update, delete on public.study_progress to authenticated;
grant select, insert on public.quiz_attempts to authenticated;

commit;

